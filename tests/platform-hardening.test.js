'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('js/quickrn-platform-hardening.js','utf8');
const values=new Map();
const events={};
const document={readyState:'complete',documentElement:{classList:{add(){}}},body:{appendChild(){}},getElementById(){return null;},createElement(){return {style:{},setAttribute(){}};},addEventListener(){}};
