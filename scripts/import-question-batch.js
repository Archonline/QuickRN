#!/usr/bin/env node
'use strict';

/*
 * Batch-import AI-produced JSON questions into the pending review queue.
 * Accepts either an array or { questions: [...] }. Validates the full batch
 * before writing any files. Input is parsed as JSON data and never evaluated.
 *
 * Usage:
 *   node scripts/import-question-batch.js ai-question-batch.json
 *   node scripts/import-question-batch.js ai-question-batch.json --submitted-by educator-draft
 */
const fs = require('fs');
const path = require('path');
const schema = require('../js/quickrn-question-schema-v2.js');

const root = path.resolve(__dirname, '..');
const pendingDir = path.join(root, 'question-candidates', 'pending');
const args = process.argv.slice(2);
const inputArg = args.find(arg => !arg.startsWith('--'));
const submitterIndex = args.indexOf('--submitted-by');
const submittedBy = submitterIndex >= 0 ? args[submitterIndex + 1] : 'ai-generated-draft';

function fail(message) {
  console.error('Batch import stopped: ' + message);
  process.exit(1);
}

function readGeneratedCandidate(file) {
  const source = fs.readFileSync(file, 'utf8');
  const prefix = "'use strict';\n\nmodule.exports = ";
  const suffix = ';\n';
  if (!source.startsWith(prefix) || !source.endsWith(suffix)) {
    throw new Error('not a data-only candidate module generated by the QuickRN importer');
  }
  return JSON.parse(source.slice(prefix.length, -suffix.length));
}

if (!inputArg) fail('Provide a JSON file containing an array or { questions: [...] }.');
if (submitterIndex >= 0 && !submittedBy) fail('Provide a value after --submitted-by.');

const inputPath = path.resolve(process.cwd(), inputArg);
if (!fs.existsSync(inputPath)) fail('Input file not found: ' + inputPath);

let payload;
try {
  payload = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
} catch (error) {
  fail('Input must be valid JSON. ' + error.message);
}

const questions = Array.isArray(payload) ? payload : payload && payload.questions;
if (!Array.isArray(questions) || questions.length === 0) {
  fail('JSON must contain a non-empty array or a non-empty "questions" array.');
}

fs.mkdirSync(pendingDir, { recursive: true });
const usedIds = new Set();
for (const file of fs.readdirSync(pendingDir).filter(name => name.endsWith('.js'))) {
  try {
    const existing = readGeneratedCandidate(path.join(pendingDir, file));
    const existingId = String(existing?.question?.metadata?.id || existing?.question?.id || '');
    if (existingId) usedIds.add(existingId);
  } catch (error) {
    fail('Cannot safely check existing pending file "' + file + '": ' + error.message);
  }
}

const prepared = [];
const errors = [];

questions.forEach((entry, index) => {
  const question = entry && entry.question && typeof entry.question === 'object'
    ? entry.question
    : entry;
  if (!question || typeof question !== 'object' || Array.isArray(question)) {
    errors.push('Item ' + (index + 1) + ': expected a question object.');
    return;
  }

  const id = String(question.metadata?.id || question.id || '').trim();
  if (!/^QR-\d{6}$/.test(id)) {
    errors.push('Item ' + (index + 1) + ': ID must match QR-######.');
    return;
  }
  if (usedIds.has(id)) {
    errors.push('Item ' + (index + 1) + ': duplicate ID ' + id + ' (pending queue or this batch).');
    return;
  }

  let normalized;
  try {
    normalized = schema.normalize({ ...question });
    const issues = schema.validate(normalized, 0);
    if (issues.length) {
      errors.push('Item ' + (index + 1) + ' (' + id + '): ' +
        issues.map(issue => issue.code + ': ' + issue.message).join('; '));
      return;
    }
  } catch (error) {
    errors.push('Item ' + (index + 1) + ' (' + id + '): ' + error.message);
    return;
  }

  usedIds.add(id);
  const candidate = {
    review: {
      status: 'pending_review',
      submittedAt: new Date().toISOString(),
      submittedBy,
      reviewer: null,
      reviewedAt: null,
      decisionNote: ''
    },
    question: normalized
  };
  prepared.push({
    id,
    filename: id.toLowerCase() + '.js',
    source: "'use strict';\n\nmodule.exports = " + JSON.stringify(candidate, null, 2) + ';\n'
  });
});

if (errors.length) {
  console.error('No files were written. ' + errors.length + ' validation issue(s):');
  for (const error of errors) console.error('- ' + error);
  process.exit(1);
}

const written = [];
try {
  for (const item of prepared) {
    const destination = path.join(pendingDir, item.filename);
    fs.writeFileSync(destination, item.source, { flag: 'wx' });
    written.push(destination);
  }
} catch (error) {
  for (const file of written) {
    try { fs.unlinkSync(file); } catch (_) { /* preserve original write error */ }
  }
  fail('Could not write the complete batch; newly created files were rolled back. ' + error.message);
}

console.log('Imported ' + prepared.length + ' candidate(s) into question-candidates/pending/.');
for (const item of prepared) console.log('- ' + item.id + ' (' + item.filename + ')');
console.log('All candidates are pending_review. The active question bank was not changed.');
